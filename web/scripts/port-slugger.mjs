import { regex } from 'github-slugger/regex.js';
import { writeFileSync } from 'node:fs';

const BACKSLASH = String.fromCharCode(92);
let src = regex.source;
const nulStart = '[' + BACKSLASH + '0-';
if (!src.startsWith(nulStart)) throw new Error('unexpected start: ' + src.slice(0, 10));
// .NET reads "\0" as an octal escape: spell NUL as \x00.
src = '[' + BACKSLASH + 'x00-' + src.slice(nulStart.length);
if (src.includes(BACKSLASH + '0')) throw new Error('another NUL escape left');
if (src.includes('"""')) throw new Error('raw string clash');

const cs = `// <auto-generated>
// Ported verbatim from github-slugger 2.0.0 (regex.js), ISC licence, (c) Titus Wormer.
// https://github.com/Flet/github-slugger. Regenerate: node web/scripts/port-slugger.mjs.
// .NET and JavaScript (without the "u" flag) both match UTF-16 code units, so surrogate-pair ranges behave the same.
// </auto-generated>
using System.Text.RegularExpressions;

namespace Lld.Content.Authoring.Parsing;

internal static partial class GithubSluggerPattern
{
    /// <summary>Characters GitHub removes from heading text when it builds an anchor.</summary>
    [GeneratedRegex("""${src}""", RegexOptions.CultureInvariant)]
    public static partial Regex Removed();
}
`;
writeFileSync(
  new URL('../../src/Lld.Content.Authoring/Parsing/GithubSluggerPattern.cs', import.meta.url),
  cs,
);
console.log('pattern length', src.length);
